/* =====================================================================
 * Living Worlds - конфиг анимированного фона SmartHome
 * ---------------------------------------------------------------------
 * Это обычный файл настроек. Правь только то, что справа от "=".
 * Одна настройка - одна строка. Строку можно закомментировать: //
 * После правки просто обнови страницу на телефоне.
 *
 * Замеры на Samsung Galaxy Ace GT-S5830, Firefox 31, по 5-10 минут:
 *   nano   ~29 fps /  6 мс   - буфер 160x120, картинка грубее
 *   ace    ~20 fps / 10 мс   - буфер 213x160, красивее   <- по умолчанию
 *   low    ~15 fps           - буфер 320x240, тяжелее
 *   still  свет без анимации - самый дешёвый режим
 *   high   телефон уходил в перезагрузку. НЕ ВКЛЮЧАТЬ.
 * =================================================================== */

window.LW_CONFIG = [
	/* Профиль: still | nano | ace | low | medium | off
	   (high есть, но он валит Galaxy Ace - см. выше) */
	'profile = nano',

	/* Ограничение FPS. nano тянет ~29 fps, но 20 хватает для красивой картинки
	   и оставляет запас CPU для UI (свайпы, polling). */
	'fps = 20',

	/* Пиксели: делитель буфера, 1..8. nano = scale 4 = буфер 160x120.
	   1 = 640x480, 2 = 320x240, 3 = 213x160, 4 = 160x120 */
	'pixels = 4',

	/* Шаг освещения, секунды: как часто пересчитывается свет по часам.
	   Раз в 180 с - это один полный перерисованный кадр в три минуты. */
	'light = 180',

	/* Блит: 1 = обновлять только анимированную область, 0 = весь кадр */
	'blit = 1',

	/* Анимация: 1 = полная (вода, облака, огни), 0 = только смена света */
	'animate = 1',

	/* Сглаживание палитры: красивее, но дороже. 0 | 1 */
	'smooth = 0',

	/* Кадрирование сцены под экран: cover | contain | fill */
	'crop = cover',

	/* Своя кнопка "во весь экран": 1 | 0. В Firefox 31 такой кнопки нет,
	   и полный экран сбрасывается при каждой перезагрузке страницы.
	   Роль кнопки играет плашка статуса сервера ("Онлайн" в углу):
	   тап - в полный экран, ещё тап - обратно. Сколько угодно раз. */
	'fullscreenOnTap = 1',

	/* Что именно служит этой кнопкой. Любой CSS-селектор:
	     #status-server - плашка "Онлайн" (по умолчанию)
	     #clock-time    - сами часы
	     screen         - любой тап по экрану */
	'fsTap = #clock-time',

	/* FPS, пока открыта панель рычагов. Низкое значение нужно, чтобы
	   панель нормально скроллилась на слабом телефоне. */
	'uiFps = 6',

	/* Как часто проверять, не сменился ли месяц или погода, минуты */
	'sceneCheck = 10',

	/* 1 = этот файл главнее рычагов: что накручено в панели на телефоне,
	   игнорируется. 0 = настройки из панели важнее файла (их всегда
	   можно сбросить кнопкой "Из конфига" в самой панели). */
	'lock = 0',

	/* Лог в консоль браузера: 0 | 1 */
	'debug = 0'
].join('\n')
